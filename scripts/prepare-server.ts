/**
 * Runs before every build. On Vercel, writes the route file for the
 * pay-by-API endpoint (src/server/grade.ts); everywhere else, makes sure it
 * isn't there, because the static GitHub Pages export can't have a server
 * route. The route file is generated, so it's in .gitignore.
 */
import fs from "node:fs";
import path from "node:path";

const dir = path.join(process.cwd(), "src", "app", "api", "grade");
const file = path.join(dir, "route.ts");
if (process.env.VERCEL) {
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(
    file,
    `// Generated by scripts/prepare-server.ts on Vercel. Don't edit or commit.
export { GET, OPTIONS, POST } from "@/server/grade";
export const dynamic = "force-dynamic";
export const maxDuration = 60;
`,
  );
  console.log("Wrote the /api/grade route for Vercel.");
} else if (fs.existsSync(file)) {
  fs.rmSync(file);
  console.log("Removed the /api/grade route (static build).");
}

// The static export cannot ship middleware (next dev with output: "export"
// refuses the file too). On Vercel it restores trailing-slash redirects for
// pages, /badge/<id>.svg and the other APIs, and lets the four read endpoints
// answer with or without a slash. See src/server/slashMiddleware.ts.
const middlewareFile = path.join(process.cwd(), "src", "middleware.ts");
if (process.env.VERCEL) {
  fs.writeFileSync(
    middlewareFile,
    `// Generated by scripts/prepare-server.ts on Vercel. Don't edit or commit.
import type { NextRequest } from "next/server";
import { middleware as slashMiddleware } from "@/server/slashMiddleware";

export function middleware(request: NextRequest) {
  return slashMiddleware(request);
}
`,
  );
  console.log("Wrote src/middleware.ts for Vercel.");
} else if (fs.existsSync(middlewareFile)) {
  fs.rmSync(middlewareFile);
  console.log("Removed src/middleware.ts (static build).");
}


